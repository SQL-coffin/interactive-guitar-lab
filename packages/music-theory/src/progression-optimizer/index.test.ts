import { describe, expect, it } from "vitest";
import { buildChord } from "../chords/index.js";
import { STANDARD_GUITAR_TUNING } from "../fretboard/index.js";
import { searchVoicings, validateVoicing, type Voicing, type VoicingNote } from "../voicings/index.js";
import { optimizeVoicingProgression, scoreVoicingTransition } from "./index.js";

function makeVoicing(chordSymbol: string, frets: Array<number | null>, score: number): Voicing {
  const strings = frets.map((fret, index): VoicingNote | null => {
    if (fret === null) return null;
    const midi = STANDARD_GUITAR_TUNING[index]! + fret;
    return {
      string: index + 1,
      fret,
      midi,
      pitchClass: ((midi % 12) + 12) % 12,
      noteName: "A",
      degree: "1",
      chordToneSpelling: "A",
    };
  });
  const notes = strings.filter((note): note is VoicingNote => note !== null);
  const fretted = notes.filter((note) => note.fret > 0).map((note) => note.fret);
  return {
    chordSymbol,
    strings,
    notes,
    frettedNotes: fretted.length,
    fretSpan: fretted.length ? Math.max(...fretted) - Math.min(...fretted) : 0,
    lowestFret: fretted.length ? Math.min(...fretted) : 0,
    highestFret: fretted.length ? Math.max(...fretted) : 0,
    missingDegrees: [],
    score,
  };
}

describe("progression voicing optimizer", () => {
  it("prefers a smooth progression over independently lowest-scored candidates", () => {
    const aAtLowPosition = makeVoicing("Amaj7", [2, 2, 2, 2, 2, 0], 0);
    const aAtHighPosition = makeVoicing("Amaj7", [9, 9, 9, 9, 9, 0], 4);
    const fSharpAtHighPosition = makeVoicing("F#m7", [9, 9, 9, 9, 9, 0], 0);
    const fSharpAtLowPosition = makeVoicing("F#m7", [2, 2, 2, 2, 2, 0], 2);

    // Independent per-chord ranking would select candidate 0 for both chords.
    const result = optimizeVoicingProgression([
      [aAtLowPosition, aAtHighPosition],
      [fSharpAtHighPosition, fSharpAtLowPosition],
    ], { limit: 4 });

    expect(result.results[0]!.steps.map((step) => step.candidateIndex)).toEqual([0, 1]);
    expect(result.results[0]!.steps[1]!.transitionCost).toBe(0);
    expect(result.results[0]!.totalCost).toBeLessThan(
      aAtLowPosition.score * 0.35 + fSharpAtHighPosition.score * 0.35
        + scoreVoicingTransition(aAtLowPosition, fSharpAtHighPosition),
    );
  });

  it("returns the requested number of distinct paths in ascending cost order", () => {
    const layers = [
      [
        makeVoicing("Amaj7", [2, 2, 2, 2, 2, 0], 0),
        makeVoicing("Amaj7", [5, 5, 5, 5, 5, 0], 1),
      ],
      [
        makeVoicing("F#m7", [2, 2, 2, 2, 2, 0], 0),
        makeVoicing("F#m7", [5, 5, 5, 5, 5, 0], 1),
      ],
    ];
    const result = optimizeVoicingProgression(layers, { limit: 3 });

    expect(result.results).toHaveLength(3);
    expect(result.results.every((path) => path.steps.length === 2)).toBe(true);
    expect(result.results.map((path) => path.totalCost)).toEqual(
      [...result.results.map((path) => path.totalCost)].sort((a, b) => a - b),
    );
    expect(result.candidateCounts).toEqual([2, 2]);
    expect(result.pathExtensionsEvaluated).toBeGreaterThan(0);
  });

  it("integrates with real candidates generated by the existing chord engine", () => {
    const a = searchVoicings("A", "major7", { maxFret: 7, limit: 4 });
    const fSharp = searchVoicings("F#", "minor7", { maxFret: 7, limit: 4 });
    const result = optimizeVoicingProgression([a.results, fSharp.results], { limit: 3 });

    expect(result.results).toHaveLength(3);
    for (const path of result.results) {
      expect(path.steps.map((step) => step.chordSymbol)).toEqual(["AMaj7", "F#m7"]);
      expect(validateVoicing(path.steps[0]!.voicing, a.chord, a.options).valid).toBe(true);
      expect(validateVoicing(path.steps[1]!.voicing, fSharp.chord, fSharp.options).valid).toBe(true);
    }
  });

  it("is deterministic and rejects empty layers or invalid weights", () => {
    const layers = [[makeVoicing("Amaj7", [2, 2, 2, 2, 2, 0], 0)]];
    const first = optimizeVoicingProgression(layers);
    const second = optimizeVoicingProgression(layers);
    expect(first.results[0]!.totalCost).toBe(second.results[0]!.totalCost);
    expect(() => optimizeVoicingProgression([])).toThrow(RangeError);
    expect(() => optimizeVoicingProgression([[]])).toThrow(RangeError);
    expect(() => optimizeVoicingProgression(layers, { positionShiftWeight: -1 })).toThrow(RangeError);
  });

  it("can compare alternate audio-derived chord hypotheses in the same layer", () => {
    const likely = makeVoicing("Amaj7", [2, 2, 2, 2, 2, 0], 0);
    const unlikely = makeVoicing("C", [2, 2, 2, 2, 2, 0], 0);
    const next = makeVoicing("F#m7", [2, 2, 2, 2, 2, 0], 0);
    const result = optimizeVoicingProgression([
      [
        { voicing: likely, chordConfidence: 0.95 },
        { voicing: unlikely, chordConfidence: 0.2 },
      ],
      [next],
    ]);

    expect(result.results[0]!.steps[0]!.chordSymbol).toBe("Amaj7");
    expect(result.results[0]!.steps[0]!.chordConfidence).toBe(0.95);
    expect(result.results[0]!.steps[0]!.chordPenalty).toBeCloseTo(1.0);
  });
});
